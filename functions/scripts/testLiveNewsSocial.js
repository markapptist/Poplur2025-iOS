const assert = require('node:assert/strict');
const { parseSocialFeed, NEWS_ACCOUNTS } = require('../lib/liveNewsSocial');
const { preserveLiveNewsIds } = require('../lib/liveNewsCore');
const account = NEWS_ACCOUNTS[3], now = Date.parse('2026-09-12T16:00:00Z');
const post = { uri: `at://${account.id}/app.bsky.feed.post/abc123`, author: { did: account.id, handle: account.handle, displayName: 'FRANCE 24', avatar: 'https://cdn.bsky.app/avatar' }, record: { text: 'Reporting #CélineDion', createdAt: '2026-09-12T15:00:00Z', facets: [{ features: [{ $type: 'app.bsky.richtext.facet#tag', tag: 'CélineDion' }] }] }, embed: { $type: 'app.bsky.embed.video#view', thumbnail: 'https://video.bsky.app/thumb.jpg' } };
const parse = p => parseSocialFeed({ feed: [{ post: p }] }, account, now);
const [event] = parse(post);
assert.equal(event.author.handle, 'france24.com');
assert.equal(event.coords, null);
assert.deepEqual(event.hashtags, ['CélineDion']);
assert.equal(event.media[0].embedUrl, `https://embed.bsky.app/embed/${account.id}/app.bsky.feed.post/abc123`);
assert.equal(parse({ ...post, author: { ...post.author, did: 'did:plc:imposter' } }).length,0);
assert.equal(parse({ ...post, author: { ...post.author, handle: 'other.example' } }).length,0);
assert.equal(parse({ ...post, record: { ...post.record, createdAt: '2025-01-01' } }).length,0);
assert.equal(parse({ ...post, labels: [{ val: 'porn' }] }).length,0);
assert.equal(parseSocialFeed({ feed: [{ post, reason: { $type: 'repost' } }] },account,now).length,0);
assert.equal(parseSocialFeed({ feed: [{ post }, { post }] },account,now).length,1);
assert.deepEqual(parse({ ...post, embed: { ...post.embed, thumbnail: 'http://localhost/x' } })[0].media,[]);
const next = { ...event, id: 'different', sources: [{ publisher:'Other',url:'https://bsky.app/profile/other/post/new' }] };
assert.equal(preserveLiveNewsIds([next],[event])[0].id,'different');
console.log('Social identity, freshness, hashtags, video attribution, moderation, deduplication, unsafe media and stable ID checks passed.');
