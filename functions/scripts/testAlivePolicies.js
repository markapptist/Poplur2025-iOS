const assert = require('node:assert/strict');
const { spatialPostSelection, MAP_POSTS_PER_CELL, MAP_VISIBLE_POSTS } = require('../lib/mapDiscoveryPolicy');
const { radiusReminderDue, RADIUS_REMINDER_COOLDOWN_MS } = require('../lib/radiusReminderPolicy');
const crowded = Array.from({ length: 120 }, (_, i) => ({ postId: `a${i}`, cellId: 'a' }));
const nearby = Array.from({ length: 40 }, (_, i) => ({ postId: `b${i}`, cellId: 'b' }));
const visible = spatialPostSelection([...crowded, ...nearby], 'a119');
assert.equal(visible[0].postId, 'a119');
assert.equal(visible.filter(p => p.cellId === 'a').length, MAP_POSTS_PER_CELL);
assert.equal(visible.filter(p => p.cellId === 'b').length, MAP_POSTS_PER_CELL);
const many = spatialPostSelection(Array.from({ length: 10_000 }, (_, i) => ({ postId: String(i), cellId: String(i % 100) })));
assert.equal(many.length, MAP_VISIBLE_POSTS);
assert.equal(new Set(many.map(p => p.cellId)).size, 100);
assert.equal(new Set(many.map(p => p.postId)).size, 100);
const now = Date.UTC(2026, 8, 8);
assert.equal(radiusReminderDue(undefined, now), true);
assert.equal(radiusReminderDue(now - 1, now), false);
assert.equal(radiusReminderDue(now - RADIUS_REMINDER_COOLDOWN_MS, now), true);
assert.equal(radiusReminderDue(now + 1, now), false);
console.log('Alive Map density and daily reminder policy checks passed');
